# 构建 Android APK（Windows 免符号链接方案）
#
# 背景：本机非管理员，Tauri CLI 在 jniLibs 创建符号链接会失败（需开发者模式/UAC）。
# 流程：tauri CLI 只负责编译 Rust .so（让它跑到 symlink 之前），随后脚本把 .so
# 复制进 gen/android/app/src/main/jniLibs，再直接调用 Gradle 打包。
# gen/android/buildSrc 的 BuildTask 已改为 no-op，Gradle 不会再次调用 Tauri CLI。
#
# 用法：
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\build-android-apk.ps1
#   -Abi x86_64|arm64-v8a|armeabi-v7a|x86 （默认 x86_64，模拟器）
#   -Release 构建 release（默认 debug）
[CmdletBinding()]
param(
    [ValidateSet("x86_64", "arm64-v8a", "armeabi-v7a", "x86")]
    [string]$Abi = "x86_64",
    [switch]$Release
)

$ErrorActionPreference = "Continue"
$root = Split-Path -Parent $PSScriptRoot
Set-Location -LiteralPath $root

$jdk = "C:\Program Files\Eclipse Adoptium\jdk-21.0.13.9-hotspot"
$sdk = Join-Path $env:LOCALAPPDATA "Android\Sdk"
if (-not (Test-Path $jdk)) { throw "JDK 21 未找到：$jdk" }
if (-not (Test-Path $sdk)) { throw "Android SDK 未找到：$sdk" }

$env:JAVA_HOME = $jdk
$env:ANDROID_HOME = $sdk
$env:ANDROID_SDK_ROOT = $sdk
$env:NDK_HOME = Join-Path $sdk "ndk\29.0.14206865"
$env:PATH = "$jdk\bin;$sdk\platform-tools;$sdk\cmdline-tools\latest\bin;$env:USERPROFILE\.cargo\bin;$env:PATH"
$env:CI = "true"

$targetMap = @{
    "x86_64"      = @{ cli = "x86_64"; rust = "x86_64-linux-android"; jni = "x86_64" }
    "arm64-v8a"   = @{ cli = "aarch64"; rust = "aarch64-linux-android"; jni = "arm64-v8a" }
    "armeabi-v7a" = @{ cli = "armv7"; rust = "armv7-linux-androideabi"; jni = "armeabi-v7a" }
    "x86"         = @{ cli = "i686"; rust = "i686-linux-android"; jni = "x86" }
}
$target = $targetMap[$Abi]
if (-not $target) { throw "未知 ABI：$Abi" }

$androidProject = Join-Path $root "src-tauri\gen\android"
$buildTaskFile = Join-Path $androidProject "buildSrc\src\main\java\com\jusong\reader\kotlin\BuildTask.kt"
$buildTaskTemplate = Join-Path $root "scripts\android\BuildTask.kt.template"
$appGradle = Join-Path $androidProject "app\build.gradle.kts"

function Repair-AndroidProject {
    # tauri android build 可能重写生成文件：恢复 no-op BuildTask，并把 compileSdk/targetSdk 降到已安装的 36。
    Copy-Item -LiteralPath $buildTaskTemplate -Destination $buildTaskFile -Force
    $content = [System.IO.File]::ReadAllText($appGradle)
    $content = $content -replace "compileSdk = 37", "compileSdk = 36" -replace "targetSdk = 37", "targetSdk = 36"
    [System.IO.File]::WriteAllText($appGradle, $content, (New-Object System.Text.UTF8Encoding($false)))
    $localProps = Join-Path $androidProject "local.properties"
    [System.IO.File]::WriteAllText(
        $localProps,
        "sdk.dir=$($sdk.Replace('\', '\\').Replace(':', '\:'))`n",
        (New-Object System.Text.UTF8Encoding($false))
    )

    # 版本号：三段 semver，第三段 = 出包次数；Android versionCode 用单调整数映射。
    $package = Get-Content (Join-Path $root "package.json") -Raw | ConvertFrom-Json
    $parts = ([string]$package.version).Split(".")
    $major = [int]$parts[0]
    $minor = [int]$parts[1]
    $build = if ($parts.Length -gt 2) { [int]$parts[2] } else { 0 }
    $versionCode = $major * 1000000 + $minor * 10000 + $build * 100
    $tauriProperties = Join-Path $androidProject "app\tauri.properties"
    [System.IO.File]::WriteAllText(
        $tauriProperties,
        "# generated by scripts/build-android-apk.ps1`ntauri.android.versionName=$($package.version)`ntauri.android.versionCode=$versionCode`n",
        (New-Object System.Text.UTF8Encoding($false))
    )
}

Write-Host "== 1/4 前端 + 种子包 ==" -ForegroundColor Cyan
& pnpm build:app
if ($LASTEXITCODE -ne 0) { throw "前端构建失败" }

Write-Host "== 2/4 编译 Rust .so（以 tauri CLI 跑到 symlink 之前）==" -ForegroundColor Cyan
# 预期该命令会在 jniLibs symlink 处失败；只要 .so 生成即可。
$debugFlag = if ($Release) { @() } else { @("--debug") }
& pnpm tauri android build --apk --ci @debugFlag --target $target.cli 2>&1 | Select-Object -Last 12
$soPath = Join-Path $root "src-tauri\target\$($target.rust)\$(if ($Release) { 'release' } else { 'debug' })\libjusong_lib.so"
if (-not (Test-Path $soPath)) {
    throw "Rust 库未生成：$soPath"
}
Write-Host ("  libjusong_lib.so = {0:N0} bytes" -f (Get-Item $soPath).Length)

Repair-AndroidProject
Write-Host "  已恢复 BuildTask no-op、compileSdk/targetSdk=36、local.properties"

Write-Host "== 3/4 复制 .so 到 jniLibs ==" -ForegroundColor Cyan
$jniDir = Join-Path $root "src-tauri\gen\android\app\src\main\jniLibs\$($target.jni)"
New-Item -ItemType Directory -Force -Path $jniDir | Out-Null
Copy-Item -LiteralPath $soPath -Destination (Join-Path $jniDir "libjusong_lib.so") -Force
Write-Output "  -> $jniDir\libjusong_lib.so"

Write-Host "== 4/4 Gradle assemble ==" -ForegroundColor Cyan
$buildType = if ($Release) { "Release" } else { "Debug" }
$taskName = "assembleUniversal$buildType"
$gradlew = Join-Path $androidProject "gradlew.bat"
Push-Location $androidProject
try {
    Write-Host "  运行任务：$taskName"
    & $gradlew $taskName --no-daemon
    if ($LASTEXITCODE -ne 0) { throw "Gradle 构建失败（exit $LASTEXITCODE）" }
} finally {
    Pop-Location
}

$apkRoot = Join-Path $root "src-tauri\gen\android\app\build\outputs\apk"
$apks = Get-ChildItem $apkRoot -Recurse -Filter *.apk -ErrorAction SilentlyContinue | Sort-Object LastWriteTime -Descending
if (-not $apks) { throw "没有找到 APK 产物：$apkRoot" }
Write-Host ""
Write-Host "APK 产物：" -ForegroundColor Green
$apks | Select-Object -First 5 | ForEach-Object { Write-Host ("  {0}  {1:N0} bytes" -f $_.FullName, $_.Length) }
